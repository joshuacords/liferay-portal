package com.liferay.osb.koroneiki.phloem.rest.internal.odata.entity.v1_0;

import com.liferay.portal.kernel.search.Field;
import com.liferay.portal.odata.entity.BooleanEntityField;
import com.liferay.portal.odata.entity.EntityField;
import com.liferay.portal.odata.entity.EntityModel;
import com.liferay.portal.odata.entity.StringEntityField;

import java.util.Map;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * @author Amos Fong
 */
public class ContactRoleEntityModel implements EntityModel {

	public static final String NAME = "ContactRole";

	public ContactRoleEntityModel() {
		_entityFieldsMap = Stream.of(
			new StringEntityField("description", locale -> "description"),
			new StringEntityField(
				"name", locale -> Field.getSortableFieldName("name")),
			new BooleanEntityField("system", locale -> "system"),
			new StringEntityField("type", locale -> "type")
		).collect(
			Collectors.toMap(EntityField::getName, Function.identity())
		);
	}

	@Override
	public Map<String, EntityField> getEntityFieldsMap() {
		return _entityFieldsMap;
	}

	@Override
	public String getName() {
		return NAME;
	}

	private final Map<String, EntityField> _entityFieldsMap;

}